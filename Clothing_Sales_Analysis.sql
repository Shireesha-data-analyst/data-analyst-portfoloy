B.Item Analysis


---->Find total quantity sold for each item.

SELECT ITEM,
SUM(QUANTITY) AS TOTAL_QUANTITY_SOLD
FROM CLOTHING
GROUP BY ITEM

---->Find total sales for each item.

SELECT ITEM,
SUM(TOTALSALES) AS TOTAL_SALES
FROM CLOTHING
GROUP BY ITEM

---->Identify the highest-selling item based on sales revenue.

SELECT TOP 1 ITEM,
SUM(TOTALSALES) AS REVENUE
FROM CLOTHING
GROUP BY ITEM
ORDER BY REVENUE DESC

---->Identify the lowest-selling item based on sales revenue.

SELECT TOP 1
ITEM,
SUM(TOTALSALES) AS REVENUE
FROM CLOTHING
GROUP BY ITEM
ORDER BY REVENUE ASC

---->Identify the most frequently sold item based on quantity.

SELECT TOP 1
ITEM,
SUM(QUANTITY) AS MOST_SOLD
FROM CLOTHING
GROUP BY ITEM
ORDER BY MOST_SOLD DESC

---->Find the average price of each item.

SELECT ITEM,
AVG(PRICE) AS AVG_PRICE
FROM CLOTHING
GROUP BY ITEM

---->Find the sales contribution of each item as a percentage of total sales.

SELECT
ITEM,
SUM(TOTALSALES) AS TOTAL_SALES,
SUM(TOTALSALES) * 100.0 /
(SELECT SUM(TOTALSALES) FROM CLOTHING) AS SALES_PERCENTAGE
FROM CLOTHING
GROUP BY ITEM


C. Store Analysis

---->Find total sales for each store.

SELECT STORE,
SUM(TOTALSALES) AS TOTAL_SALES
FROM CLOTHING
GROUP BY STORE

---->Find total quantity sold by each store.

SELECT STORE,
SUM(QUANTITY) AS TOTAL_QUANTITY_SOLD
FROM CLOTHING
GROUP BY STORE

---->Identify the store with the highest sales.

SELECT TOP 1 STORE,
SUM(TOTALSALES) AS HIGHEST_sALES
FROM CLOTHING
GROUP BY STORE
ORDER BY HIGHEST_SALES DESC

---->Identify the store with the lowest sales.

SELECT TOP 1 STORE,
SUM(TOTALSALES) AS LOWEST_sALES
FROM CLOTHING
GROUP BY STORE
ORDER BY LOWEST_SALES ASC

---->Calculate the average order value for each store.

SELECT
STORE,
AVG(ORDER_TOTAL) AS AVERAGE_ORDER_VALUE
FROM
(
SELECT
STORE,
INVOICENO,
SUM(TOTALSALES) AS ORDER_TOTAL
FROM CLOTHING
GROUP BY STORE, INVOICENO
) AS ORDERS
GROUP BY STORE

---->Find the best-performing item in each store.

SELECT C.ITEM,
C.STORE
FROM
(
SELECT ITEM, 
STORE,
SUM(TOTALSALES) AS TOTAL_sALES,
ROW_NUMBER()OVER(PARTITION BY STORE ORDER BY SUM(TOTALSALES) DESC) AS ROW_NUM
FROM CLOTHING
GROUP BY ITEM,STORE
)
AS C
WHERE C.ROW_NUM=1

---->Find the lowest-performing item in each store.

SELECT C.ITEM,
C.STORE
FROM
(
SELECT ITEM, 
STORE,
SUM(TOTALSALES) AS TOTAL_sALES,
ROW_NUMBER()OVER(PARTITION BY STORE ORDER BY SUM(TOTALSALES) ASC) AS ROW_NUM
FROM CLOTHING
GROUP BY ITEM,STORE
)
AS C
WHERE C.ROW_NUM=1

