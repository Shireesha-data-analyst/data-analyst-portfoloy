----->48. Find the month with highest sales for each year.


SELECT
    C.YEAR_NO,
    C.MONTH_NO,
    C.TOTAL_SALES
FROM
(
    SELECT
        DATEPART(YEAR, TRY_CONVERT(DATE, DATE)) AS YEAR_NO,
        DATEPART(MONTH, TRY_CONVERT(DATE, DATE)) AS MONTH_NO,
        SUM(TOTALSALES) AS TOTAL_SALES,
        ROW_NUMBER() OVER
        (
            PARTITION BY DATEPART(YEAR, TRY_CONVERT(DATE, DATE))
            ORDER BY SUM(TOTALSALES) DESC
        ) AS ROW_NUM
    FROM CLOTHING
    GROUP BY
        DATEPART(YEAR, TRY_CONVERT(DATE, DATE)),
        DATEPART(MONTH, TRY_CONVERT(DATE, DATE))
) AS C
WHERE C.ROW_NUM = 1


----->49. Find cumulative sales by date.

SELECT
    TRY_CONVERT(DATE, DATE) AS SALES_DATE,
    SUM(TOTALSALES) AS DAILY_SALES,
    SUM(SUM(TOTALSALES)) OVER
    (
        ORDER BY TRY_CONVERT(DATE, DATE)
    ) AS CUMULATIVE_SALES
FROM CLOTHING
GROUP BY TRY_CONVERT(DATE, DATE)
ORDER BY SALES_DATE


----->50. Find percentage contribution of each item within each store.


SELECT
    STORE,
    ITEM,
    SUM(TOTALSALES) AS ITEM_SALES,
    SUM(TOTALSALES) * 100.0 /
    SUM(SUM(TOTALSALES)) OVER
    (
        PARTITION BY STORE
    ) AS SALES_PERCENTAGE
FROM CLOTHING
GROUP BY STORE, ITEM
