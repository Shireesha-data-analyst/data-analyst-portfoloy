E. Time-Based Analysis


---->Find total sales for each month.

SELECT 
DATEPART(MONTH,TRY_CONVERT(DATE,DATE)) AS MONTH_NO,
SUM(TOTALSALES) AS TOTAL_SALES
FROM CLOTHING
GROUP BY DATEPART(MONTH,TRY_CONVERT(DATE,DATE)) 


---->Identify highest-sales month.

SELECT TOP 1
DATEPART(MONTH,TRY_CONVERT(DATE,DATE)) AS MONTH_NO,
SUM(TOTALSALES) AS HIGHEST_SALES
FROM CLOTHING
GROUP BY DATEPART(MONTH,TRY_CONVERT(DATE,DATE))
ORDER BY HIGHEST_SALES DESC

---->Identify lowest-sales month.

SELECT TOP 1
DATEPART(MONTH,TRY_CONVERT(DATE,DATE)) AS MONTH_NO,
SUM(TOTALSALES) AS LOWEST_SALES
FROM CLOTHING
GROUP BY DATEPART(MONTH,TRY_CONVERT(DATE,DATE))
ORDER BY LOWEST_SALES ASC

---->Find total quantity sold for each month.

SELECT DATEPART(MONTH,TRY_CONVERT(DATE,DATE)) AS MONTH_NO,
SUM(QUANTITY) AS TOTAL_QUANTITY
FROM CLOTHING
GROUP BY DATEPART(MONTH,TRY_CONVERT(DATE,DATE))
ORDER BY MONTH_NO ASC

---->Find average sales per month.

SELECT
AVG(MONTHLY_SALES) AS AVG_SALES_PER_MONTH
FROM
(
SELECT
DATEPART(MONTH, TRY_CONVERT(DATE, DATE)) AS MONTH_NO,
SUM(TOTALSALES) AS MONTHLY_SALES
FROM CLOTHING
GROUP BY
DATEPART(MONTH, TRY_CONVERT(DATE, DATE))
) AS M

---->Find total sales for each year.

SELECT 
DATEPART(YEAR,TRY_CONVERT(DATE,DATE)) AS MONTH_NO,
SUM(TOTALSALES) AS TOTAL_SALES
FROM CLOTHING 
GROUP BY DATEPART(YEAR,TRY_CONVERT(DATE,DATE)) 
ORDER BY MONTH_NO ASC

---->Find monthly sales by year.

SELECT
DATEPART(YEAR, TRY_CONVERT(DATE, DATE)) AS YEAR_NO,
DATEPART(MONTH, TRY_CONVERT(DATE, DATE)) AS MONTH_NO,
SUM(TOTALSALES) AS TOTAL_SALES
FROM CLOTHING
GROUP BY
DATEPART(YEAR, TRY_CONVERT(DATE, DATE)),
DATEPART(MONTH, TRY_CONVERT(DATE, DATE))
ORDER BY
YEAR_NO ASC,
MONTH_NO ASC


